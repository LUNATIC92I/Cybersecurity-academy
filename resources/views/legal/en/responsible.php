<p>Cybersecurity skills can protect or harm. This policy sets the rules every learner accepts when using the platform, and especially its practical labs.</p>
<h2>1. Authorisation first</h2>
<ul>
<li>Only test systems you own or have <strong>explicit written permission</strong> to test. Learning on the platform never grants permission to test anyone's systems.</li>
<li>Never test your employer's, school's or a third party's systems without written authorisation from someone entitled to give it.</li>
<li>If you discover a vulnerability by accident, stop and report it through the owner's disclosure process.</li>
</ul>
<h2>2. Lab environments</h2>
<ul>
<li><strong>Browser-based simulations</strong> use synthetic data and run entirely on the platform. They contain no real personal data.</li>
<li><strong>Downloadable datasets</strong> are synthetic or sanitised. Do not attempt to re-identify anyone from them.</li>
<li><strong>Self-hosted virtual labs</strong> (intentionally vulnerable applications) must run only on infrastructure you control, isolated from production networks and from the internet where possible. The platform documents how to deploy them but does not operate them for you.</li>
<li>Labs marked <em>elevated risk</em> require you to confirm these conditions before starting; your acknowledgement is recorded.</li>
</ul>
<h2>3. Safe practice</h2>
<ul>
<li>Do not run destructive actions, denial-of-service or persistence outside a disposable lab.</li>
<li>Treat any captured file as potentially malicious; analyse it only in an isolated environment.</li>
<li>Follow each lab's cleanup instructions and destroy lab environments when finished.</li>
</ul>
<h2>4. Course completion never requires harm</h2>
<p>No course requires destructive exploitation, attacks on third parties or access to real personal data.</p>
<h2>5. Enforcement</h2>
<p>Breaching this policy may lead to account suspension and revocation of certificates. Illegal activity may be reported to the competent authorities.</p>
