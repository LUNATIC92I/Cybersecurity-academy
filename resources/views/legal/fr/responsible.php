<p>Les compétences en cybersécurité peuvent protéger ou nuire. Cette politique fixe les règles que chaque apprenant accepte en utilisant la plateforme, et en particulier ses labs pratiques.</p>
<h2>1. L'autorisation d'abord</h2>
<ul>
<li>Ne testez que des systèmes qui vous appartiennent ou pour lesquels vous disposez d'une <strong>autorisation écrite explicite</strong>. Se former sur la plateforme n'autorise jamais à tester les systèmes de qui que ce soit.</li>
<li>Ne testez jamais les systèmes de votre employeur, de votre école ou d'un tiers sans autorisation écrite d'une personne habilitée à la donner.</li>
<li>Si vous découvrez une vulnérabilité par hasard, arrêtez-vous et signalez-la selon la procédure de divulgation du propriétaire.</li>
</ul>
<h2>2. Environnements de lab</h2>
<ul>
<li>Les <strong>simulations dans le navigateur</strong> utilisent des données synthétiques et s'exécutent entièrement sur la plateforme. Elles ne contiennent aucune donnée personnelle réelle.</li>
<li>Les <strong>jeux de données téléchargeables</strong> sont synthétiques ou anonymisés. N'essayez pas de réidentifier qui que ce soit.</li>
<li>Les <strong>labs virtuels auto-hébergés</strong> (applications volontairement vulnérables) doivent fonctionner uniquement sur une infrastructure que vous contrôlez, isolée des réseaux de production et d'Internet dans la mesure du possible. La plateforme documente leur déploiement mais ne les exploite pas pour vous.</li>
<li>Les labs signalés <em>à risque élevé</em> exigent que vous confirmiez ces conditions avant de commencer ; votre engagement est enregistré.</li>
</ul>
<h2>3. Bonnes pratiques</h2>
<ul>
<li>N'exécutez aucune action destructrice, aucun déni de service ni aucune persistance en dehors d'un lab jetable.</li>
<li>Considérez tout fichier capturé comme potentiellement malveillant ; analysez-le uniquement dans un environnement isolé.</li>
<li>Suivez les instructions de nettoyage de chaque lab et détruisez les environnements une fois terminé.</li>
</ul>
<h2>4. La réussite d'un cours n'exige jamais de nuire</h2>
<p>Aucun cours n'exige d'exploitation destructrice, d'attaque contre des tiers ni d'accès à des données personnelles réelles.</p>
<h2>5. Application</h2>
<p>Le non-respect de cette politique peut entraîner la suspension du compte et la révocation des certificats. Toute activité illégale peut être signalée aux autorités compétentes.</p>
