<?php

declare(strict_types=1);

namespace Database;

use App\Core\Database;

/**
 * Applies versioned SQL files from database/migrations in filename order and
 * records them in schema_migrations, so each file runs exactly once.
 */
final class Migrator
{
    public function __construct(private readonly Database $db, private readonly string $directory)
    {
    }

    public function migrate(?callable $output = null): array
    {
        $this->ensureTable();
        $applied = $this->db->column('SELECT migration FROM schema_migrations');
        $ran = [];
        foreach ($this->files() as $file) {
            $name = basename($file);
            if (in_array($name, $applied, true)) {
                continue;
            }
            foreach ($this->statements((string) file_get_contents($file)) as $statement) {
                $this->db->pdo()->exec($statement);
            }
            $this->db->insert('schema_migrations', ['migration' => $name, 'applied_at' => gmdate('Y-m-d H:i:s')]);
            $ran[] = $name;
            $output && $output("Migrated: $name");
        }
        return $ran;
    }

    public function dropAll(): void
    {
        $pdo = $this->db->pdo();
        $pdo->exec('SET FOREIGN_KEY_CHECKS = 0');
        foreach ($this->db->column('SHOW TABLES') as $table) {
            if (preg_match('/^[a-zA-Z0-9_]+$/', (string) $table)) {
                $pdo->exec("DROP TABLE IF EXISTS `$table`");
            }
        }
        $pdo->exec('SET FOREIGN_KEY_CHECKS = 1');
    }

    /**
     * Concatenate migrations into a single schema file (database.sql).
     */
    public function dump(string $target): void
    {
        $sql = "-- Cybersecurity-Academy full schema (generated by `php bin/console schema:dump`).\n"
            . "-- Prefer `php bin/console migrate` which also tracks applied versions.\n\n"
            . "SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;\n\n";
        foreach ($this->files() as $file) {
            $sql .= '-- ' . basename($file) . "\n" . trim((string) file_get_contents($file)) . "\n\n";
        }
        $sql .= "SET FOREIGN_KEY_CHECKS = 1;\n";
        file_put_contents($target, $sql);
    }

    private function ensureTable(): void
    {
        $this->db->pdo()->exec(
            'CREATE TABLE IF NOT EXISTS schema_migrations (
                migration VARCHAR(190) PRIMARY KEY,
                applied_at DATETIME NOT NULL
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci'
        );
    }

    private function files(): array
    {
        $files = glob($this->directory . '/*.sql') ?: [];
        sort($files, SORT_STRING);
        return $files;
    }

    private function statements(string $sql): array
    {
        $lines = array_filter(
            explode("\n", $sql),
            fn ($line) => !str_starts_with(ltrim($line), '--')
        );
        $parts = preg_split('/;\s*(?:\n|$)/', implode("\n", $lines)) ?: [];
        return array_values(array_filter(array_map('trim', $parts), fn ($s) => $s !== ''));
    }
}
